/**
 * A glyph, what Unicode calls it, and the space-separated words that find it.
 *
 * The name is the one from Unicode's own emoji list rather than anything
 * invented here, so what a card says a reaction is matches what every other
 * app calls it. It is lower case as Unicode writes it; anywhere it starts a
 * line it is capitalised where it is shown.
 */
export type EmojiEntry = readonly [emoji: string, name: string, terms: string];

export interface EmojiGroup {
  /** Tab label, and the accessible name of the tab. */
  name: string;
  /** The glyph on the tab itself. */
  icon: string;
  emojis: readonly EmojiEntry[];
}

