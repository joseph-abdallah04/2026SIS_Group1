/** Every emoji the picker offers, flattened. */
export const ALL_PICKER_EMOJIS: readonly string[] = EMOJI_GROUPS.flatMap((group) =>
  group.emojis.map(([emoji]) => emoji),
);

/** The whole catalogue as one flat list, for searching across categories. */
const ALL_ENTRIES: readonly EmojiEntry[] = EMOJI_GROUPS.flatMap((group) => group.emojis);

const NAMES = new Map<string, string>(ALL_ENTRIES.map(([emoji, name]) => [emoji, name]));

/**
 * What one emoji is called, for anywhere a glyph alone is not enough — the
 * list of who reacted, which is headed by the reaction it belongs to.
 *
 * Null for anything not in the catalogue. A reaction can be any emoji the
 * server accepts, so one can arrive from a client offering a wider set than
 * this one, or in a form this list does not carry (a skin tone, say). Nothing
 * is invented for those: the heading is dropped and the names stand alone.
 */
export function emojiName(emoji: string): string | null {
  return NAMES.get(emoji) ?? null;
}

/**
 * What a button that leaves this reaction is called, for anyone who cannot see
 * the glyph on it.
 *
 * The shared contract can only manage "React with 🎉": it knows the quick
 * three by name and nothing else, and a screen reader handed the bare glyph
 * falls back to whatever its own table calls it — which is why the heading
 * over a list of names and the name announced for the same chip used to
 * disagree. The catalogue is here, so the button can say what it is.
 */
export function reactionButtonLabel(emoji: string): string {
  const named = reactionName(emoji);
  if (named) return named;
  const known = emojiName(emoji);
  return known ? `React with ${known}` : reactionLabel(emoji);
}

/**
 * Emoji whose terms match every word typed, in catalogue order.
 *
 * Each typed word has to match the *start* of one of an emoji's terms, so
 * "car" finds the car and the carrot but not the postcard, and "he" finds
 * hearts without also finding everything that mentions "the". Several words
 * narrow rather than widen: "red heart" is the emoji that is both.
 */
export function searchEmojis(query: string): readonly EmojiEntry[] {
  const words = query.toLowerCase().split(/\s+/).filter(Boolean);
  if (words.length === 0) return [];

  return ALL_ENTRIES.filter(([, , terms]) => {
    const candidates = terms.split(' ');
    return words.every((word) => candidates.some((term) => term.startsWith(word)));
  });
}
